<#
.SYNOPSIS
    Nemurimouto Türkçe Yama Otomatik Kurulum ve Yapılandırma Betiği
#>

param(
    [string]$GameDir = "C:\Users\Birin\AppData\Roaming\itch\apps\nemurimouto\win_c"
)

$ErrorActionPreference = "Stop"

Write-Host "==========================================================" -ForegroundColor Cyan
Write-Host "     Nemurimouto - Türkçe Yama Kurulum Yöneticisi         " -ForegroundColor Green
Write-Host "==========================================================" -ForegroundColor Cyan

if (-not (Test-Path (Join-Path $GameDir "Nemurimouto.exe"))) {
    Write-Error "Oyun dizini geçersiz veya Nemurimouto.exe bulunamadı: $GameDir"
}

Write-Host "[1/4] Hedef oyun dizini doğrulandı: $GameDir" -ForegroundColor Green

# Dizinleri oluştur
$bepConfigDir = Join-Path $GameDir "BepInEx\config"
$bepPluginsDir = Join-Path $GameDir "BepInEx\plugins\XUnity.AutoTranslator"
$transDir = Join-Path $GameDir "BepInEx\Translation\tr\Text"

New-Item -ItemType Directory -Path $bepConfigDir -Force | Out-Null
New-Item -ItemType Directory -Path $bepPluginsDir -Force | Out-Null
New-Item -ItemType Directory -Path $transDir -Force | Out-Null
Write-Host "[2/4] BepInEx ve Çeviri dizinleri hazırlandı." -ForegroundColor Green

# Yapılandırma dosyasını kopyala
$sourceConfig = Join-Path $PSScriptRoot "AutoTranslatorConfig.ini"
$targetConfig = Join-Path $bepConfigDir "AutoTranslatorConfig.ini"
Copy-Item -Path $sourceConfig -Destination $targetConfig -Force
Write-Host "[3/4] AutoTranslatorConfig.ini hedef konuma yüklendi." -ForegroundColor Green

# Sözlük dosyasını hazırla
$sourceDict = Join-Path $PSScriptRoot "_AutoGeneratedTranslations_Sablon.txt"
$targetDict = Join-Path $transDir "_AutoGeneratedTranslations.txt"
if (Test-Path $sourceDict) {
    Copy-Item -Path $sourceDict -Destination $targetDict -Force
    Write-Host "[4/4] Başlangıç Türkçe çeviri sözlüğü aktarıldı: $targetDict" -ForegroundColor Green
}

Write-Host "`n==========================================================" -ForegroundColor Yellow
Write-Host "KURULUM BAŞARIYLA TAMAMLANDI!" -ForegroundColor Yellow
Write-Host "- Hedef Dil: Türkçe (tr)" -ForegroundColor Cyan
Write-Host "- Kaynak Dil: İngilizce (en) / Japonca (ja)" -ForegroundColor Cyan
Write-Host "- Çeviriler Konumu: $transDir\_AutoGeneratedTranslations.txt" -ForegroundColor Cyan
Write-Host "==========================================================" -ForegroundColor Yellow
