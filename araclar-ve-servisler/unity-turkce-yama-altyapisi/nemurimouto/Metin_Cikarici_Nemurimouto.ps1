<#
.SYNOPSIS
    Nemurimouto I2.Loc & Diyalog Metin Çıkarıcı ve Türkçe Çeviri Sözlüğü Oluşturucu.
.DESCRIPTION
    Nemurimouto_Data\resources.assets dosyasındaki I2Languages kaynağını tarar,
    tüm diyalog, hikaye ve arayüz metinlerini CSV ve XUnity.AutoTranslator sözlük formatında dışa aktarır.
#>

param(
    [string]$GamePath = "C:\Users\Birin\AppData\Roaming\itch\apps\nemurimouto\win_c",
    [string]$OutputDir = $PSScriptRoot
)

$ErrorActionPreference = "Stop"

$assetPath = Join-Path $GamePath "Nemurimouto_Data\resources.assets"
if (-not (Test-Path $assetPath)) {
    Write-Error "Hedef resources.assets bulunamadı: $assetPath"
}

Write-Host "[1/3] resources.assets okunuyor ($((Get-Item $assetPath).Length / 1MB | Out-String | ForEach-Object { $_.Trim() }) MB)..." -ForegroundColor Cyan
$bytes = [System.IO.File]::ReadAllBytes($assetPath)
$text = [System.Text.Encoding]::ASCII.GetString($bytes)

$pos = $text.IndexOf("I2Languages")
if ($pos -lt 0) {
    Write-Error "resources.assets içinde I2Languages verisi bulunamadı!"
}
Write-Host "I2Languages bloku tespit edildi (Offset: $pos)." -ForegroundColor Green

Write-Host "[2/3] Diyalog ve arayüz dizgileri ayrıştırılıyor..." -ForegroundColor Cyan
$slice = $text.Substring($pos, [Math]::Min(2500000, $text.Length - $pos))
$pattern = "(chat_\d+\/\d+_[a-z]+|event_[a-z]+_\d+\/\d+_[a-z]+|prologue\w*\/\d+_[a-z]+)[\x00-\x20]+([A-Z][^\x00-\x1F]{3,200})"
$regexMatches = [regex]::Matches($slice, $pattern)

$rows = @()
$autoTransLines = @()
$seenTexts = New-Object System.Collections.Generic.HashSet[string]

foreach ($m in $regexMatches) {
    $key = $m.Groups[1].Value.Trim()
    $english = $m.Groups[2].Value.Trim()
    if ($english.Length -gt 2 -and -not $seenTexts.Contains($english)) {
        $seenTexts.Add($english) | Out-Null
        $rows += [PSCustomObject]@{
            Key = $key
            English = $english
            Turkish = ""
        }
        $autoTransLines += "$english=$english"
    }
}

$csvPath = Join-Path $OutputDir "I2Languages_Ceviri_Tablosu.csv"
$rows | Export-Csv -Path $csvPath -NoTypeInformation -Encoding UTF8
Write-Host "[3/3] Çeviri tablosu kaydedildi: $csvPath (Toplam satır: $($rows.Count))" -ForegroundColor Green

$autoTransPath = Join-Path $OutputDir "_AutoGeneratedTranslations_Sablon.txt"
[System.IO.File]::WriteAllLines($autoTransPath, $autoTransLines, [System.Text.Encoding]::UTF8)
Write-Host "AutoTranslator sözlük şablonu oluşturuldu: $autoTransPath" -ForegroundColor Green
Write-Host "İşlem başarıyla tamamlandı!" -ForegroundColor Yellow

