<#
.SYNOPSIS
    My Dystopian Robot Girlfriend (Factorial Omega) - Türkçe Yama Kurulum Yöneticisi
#>

param(
    [string]$GameDir = "C:\Users\Birin\AppData\Roaming\itch\apps\factorial-omega"
)

$ErrorActionPreference = "Stop"

Write-Host "==========================================================" -ForegroundColor Cyan
Write-Host " Factorial Omega - Türkçe Yama Kurulum ve Entegratörü     " -ForegroundColor Green
Write-Host "==========================================================" -ForegroundColor Cyan

if (-not (Test-Path (Join-Path $GameDir "My Dystopian Robot Girlfriend.exe"))) {
    Write-Error "Oyun dizini geçersiz veya exe bulunamadı: $GameDir"
}

Write-Host "[1/4] Hedef oyun dizini doğrulandı: $GameDir" -ForegroundColor Green

# 1. YÖNTEM: Oyunun Yerel ModTranslations Dizinine Entegrasyon
$localLowDir = "$env:USERPROFILE\AppData\LocalLow\IncontinentCell\My Dystopian Robot Girlfriend"
$modsTransDir = Join-Path $localLowDir "ModsTranslations"
New-Item -ItemType Directory -Path $modsTransDir -Force | Out-Null

$sourceJson = Join-Path $PSScriptRoot "ModTranslation_Turkish_Template.json"
$targetJson = Join-Path $modsTransDir "Translation_tr_BaseGame.json"
Copy-Item -Path $sourceJson -Destination $targetJson -Force
Write-Host "[2/4] Yerel ModsTranslations şablonu yüklendi:" -ForegroundColor Green
Write-Host "      -> $targetJson" -ForegroundColor Gray

# 2. YÖNTEM: BepInEx 6 (IL2CPP) + XUnity.AutoTranslator Yapılandırması
$bepConfigDir = Join-Path $GameDir "BepInEx\config"
$bepPluginsDir = Join-Path $GameDir "BepInEx\plugins\XUnity.AutoTranslator"
$transDir = Join-Path $GameDir "BepInEx\Translation\tr\Text"

New-Item -ItemType Directory -Path $bepConfigDir -Force | Out-Null
New-Item -ItemType Directory -Path $bepPluginsDir -Force | Out-Null
New-Item -ItemType Directory -Path $transDir -Force | Out-Null

$sourceConfig = Join-Path $PSScriptRoot "AutoTranslatorConfig.ini"
$targetConfig = Join-Path $bepConfigDir "AutoTranslatorConfig.ini"
Copy-Item -Path $sourceConfig -Destination $targetConfig -Force
Write-Host "[3/4] BepInEx 6 (IL2CPP) AutoTranslatorConfig.ini yüklendi." -ForegroundColor Green

# AutoTranslator sözlük başlangıç dosyası
$targetTransTxt = Join-Path $transDir "_AutoGeneratedTranslations.txt"
$dictContent = @"
New Game=Yeni Oyun
Continue=Devam Et
Load Game=Oyunu Yükle
Save Game=Oyunu Kaydet
Options=Seçenekler
Settings=Ayarlar
Quit=Çıkış
Quit to Desktop=Masaüstüne Çık
Back=Geri
Inventory=Envanter
Shop=Mağaza
Display=Ekran
Audio=Ses
Language=Dil
Fullscreen=Tam Ekran
Resolution=Çözünürlük
Music Volume=Müzik Sesi
Sound Effects=Ses Efektleri
Voice Volume=Seslendirme
Apply=Uygula
Cancel=İptal
Confirm=Onayla
Yes=Evet
No=Hayır
"@
[System.IO.File]::WriteAllText($targetTransTxt, $dictContent, [System.Text.Encoding]::UTF8)
Write-Host "[4/4] BepInEx 6 sözlük dosyası hazırlandı: $targetTransTxt" -ForegroundColor Green

Write-Host "`n==========================================================" -ForegroundColor Yellow
Write-Host "KURULUM BAŞARIYLA TAMAMLANDI!" -ForegroundColor Yellow
Write-Host "- Metot 1 (Yerel Mod): $targetJson" -ForegroundColor Cyan
Write-Host "- Metot 2 (BepInEx 6 IL2CPP Hook): $transDir" -ForegroundColor Cyan
Write-Host "==========================================================" -ForegroundColor Yellow

